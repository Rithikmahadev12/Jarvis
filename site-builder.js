function extractHtml(raw) {
  let text = (raw || "").trim();
  text = text.replace(/^```(?:html)?\s*/i, "").replace(/```\s*$/i, "").trim();
  const start = text.search(/<!DOCTYPE html>|<html/i);
  if (start === -1) throw new Error("Model did not return an HTML document");
  return text.slice(start);
}

