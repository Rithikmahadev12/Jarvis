// J.A.R.V.I.S — WEBSITE BUILDER
// "hey jarvis build me a site for a coffee place" → Jarvis asks for
// a name → generates a real, self-contained single-page site (HTML
// + CSS + a little vanilla JS, no external deps) with Groq → saves
// it to disk → server.js hands the caller a same-origin preview URL
// to show in a window. "hey jarvis download <name>" later zips that
// same folder back up for the user.
// ═══════════════════════════════════════════════════════════════

const fs   = require("fs");
const path = require("path");
const archiver = require("archiver");

let Hermes = null;
try { Hermes = require("./hermes-engine"); } catch { Hermes = null; }
let LocalLLM = null;
try { LocalLLM = require("./local-llm"); } catch { LocalLLM = null; }

const SITES_DIR    = path.join(__dirname, "data", "sites");
const REGISTRY_FILE = path.join(SITES_DIR, "registry.json");
if (!fs.existsSync(SITES_DIR)) fs.mkdirSync(SITES_DIR, { recursive: true });

// ── REGISTRY ──────────────────────────────────────────────────
// Maps every site Jarvis has built this run (and across restarts)
// so a later "download <name>" can find it by name alone.
function loadRegistry() {
  try { return JSON.parse(fs.readFileSync(REGISTRY_FILE, "utf8")); }
  catch { return []; }
}
function saveRegistry(list) {
  try { fs.writeFileSync(REGISTRY_FILE, JSON.stringify(list, null, 2)); } catch { /* non-fatal */ }
}

function slugify(name) {
  const base = (name || "site")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 40) || "site";
  return `${base}-${Date.now().toString(36)}`;
}

// ── PROMPT ────────────────────────────────────────────────────
// Target bar: a self-taught design studio's flagship site — big,
// confident, editorial. Think dark cinematic coffee-brand landing
// pages, not a Bootstrap template. The model gets a LOT of creative
// license on layout; the hard rules only lock down what actually
// breaks the preview (no external assets, must be one file, must work).
//
// Two versions of this prompt exist because Groq's free/on_demand
// tier caps qwen/qwen3.6-27b at a hard 8000 TPM — and that limit is
// charged against (system + user + max_tokens requested), not just
// what's actually generated. The full prompt below plus a realistic
// output length blows straight through that. So:
//   - PROMPT_CORE (~compact) is what actually gets sent to Groq.
//   - PROMPT_FULL (core + concrete technique snippets) is reserved
//     for local Ollama generation, which has no such cap — see
//     buildSite() below, which prefers local whenever it's reachable.
const PROMPT_CORE = `You are an award-winning web designer — the kind whose portfolio gets featured on Awwwards and CSS Design Awards. A client just hired you to build ONE complete, self-contained website. Output raw HTML only.

NEVER DO THIS (instant failure):
- Never mention who or what built the site — no "built by", "powered by", "generated by", no AI/assistant/Jarvis references anywhere in the copy, meta tags, comments, or footer.
- Never ship a generic centered-hero-then-3-cards-then-footer template — that's the default failure mode, actively avoid it.
- Never use lorem ipsum or vague placeholder copy like "coming soon". Every sentence is real, specific, on-brand copy for this exact business.
- Never reference external image URLs, fonts, icon libraries, or scripts. Everything self-contained.

ART DIRECTION — commit fully to one strong point of view, don't hedge into something generic:
- Oversized, confident type scale (display headlines 80-160px+), a contrasting type pairing (heavy grotesque + delicate italic serif), system font stacks only.
- Editorial structure: numbered sections (I, II, III), small tracked-out eyebrow labels, pull quotes, asymmetric grids instead of everything centered.
- A narrow, considered 2-4 color palette that fits THIS brand's mood. Build atmosphere with CSS gradients, radial glows, grain/noise, blend modes, geometric shapes — no photography needed.
- Real interaction: scroll-triggered reveal animations (IntersectionObserver), a custom cursor if it fits, personality in hover states, a spec-sheet/index style layout for menu-or-services items instead of generic cards.
- Every business gets its OWN visual language — a coffee roaster ≠ a law firm ≠ a tattoo studio.

FUNCTIONAL RULES:
- Output ONLY the raw HTML document starting with <!DOCTYPE html>, nothing else — no fences, no commentary.
- One file: CSS in <style> in <head>, JS in <script> before </body>.
- Include <form id="contact-form"> (name/email/message). On submit: preventDefault, POST JSON to "/api/contact" via fetch, catch failures silently, always show an inline success state.
- Fully responsive from ~360px up. Real contrast. Semantic HTML, labeled fields.`;

