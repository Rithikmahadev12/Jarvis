function escapeHtml(s) {
  return String(s || "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
}

// ── BACKEND SCAFFOLD ─────────────────────────────────────────────
// A small, real Express backend written alongside the frontend so
// the site isn't just a static mockup — it has somewhere to actually
// send its contact-form submissions. This is generated deterministically
// (not by the model) so its routes always match what the frontend
// fetch() calls expect. The live preview only serves index.html as a
// static file (see server.js's /sites route); this backend is for
// when the user downloads the site and wants to actually run it.
function backendFiles(cleanName, cleanType, slug) {
  const pkg = {
    name: slug,
    version: "1.0.0",
    private: true,
    description: `Backend for ${cleanName}`,
    scripts: { start: "node server.js" },
    dependencies: { express: "^4.19.2" },
  };

  const serverJs = `// Backend for ${cleanName} (${cleanType})
// Serves the site and stores form submissions to disk.
//   npm install
//   npm start        -> http://localhost:3000
"use strict";
const express = require("express");
const fs = require("fs");
const path = require("path");

const app = express();
const PORT = process.env.PORT || 3000;
const DATA_FILE = path.join(__dirname, "submissions.json");

app.use(express.json());
app.use(express.static(__dirname));

function readSubmissions() {
  try { return JSON.parse(fs.readFileSync(DATA_FILE, "utf8")); }
  catch { return []; }
}
function saveSubmission(entry) {
  const all = readSubmissions();
  all.push(entry);
  fs.writeFileSync(DATA_FILE, JSON.stringify(all, null, 2));
}

app.post("/api/contact", (req, res) => {
  const { name, email, message } = req.body || {};
  if (!email) return res.status(400).json({ ok: false, error: "email is required" });
  saveSubmission({ name: name || "", email, message: message || "", receivedAt: new Date().toISOString() });
  res.json({ ok: true });
});

app.get("/api/submissions", (_req, res) => res.json(readSubmissions()));

app.get("/api/health", (_req, res) => res.json({ ok: true, site: ${JSON.stringify(cleanName)} }));

app.listen(PORT, () => console.log(\`${cleanName} backend running at http://localhost:\${PORT}\`));
`;

  return { "package.json": JSON.stringify(pkg, null, 2), "server.js": serverJs };
}

// ── STREAMING BUILD ───────────────────────────────────────────
// The chat tool call registers the build (instant, no network wait)
// and hands the caller a buildId; the browser then opens the OS-style
// build window and connects to /api/sites/stream/:buildId, which
// drives streamBuild() below and forwards each token to the client as
// it's generated — the window shows the actual HTML materializing
// instead of a blank screen while Groq thinks.
const pendingBuilds = new Map(); // buildId -> { businessType, name }

function startBuild(businessType, name) {
  const cleanName = (name || "").trim();
  if (!cleanName) throw new Error("A business name is required");
  const buildId = `b_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 8)}`;
  pendingBuilds.set(buildId, { businessType: (businessType || "business").trim(), name: cleanName });
  return buildId;
}

async function streamBuild(buildId, onDelta) {
  const job = pendingBuilds.get(buildId);
  if (!job) throw new Error("Unknown or already-completed build");
  pendingBuilds.delete(buildId);
  return buildSite(job.businessType, job.name, onDelta);
}

// Env var override so the site builder can use a stronger local model
// (e.g. "qwen2.5-coder:14b") for generation quality without changing
// OLLAMA_MODEL used everywhere else in Jarvis for quick chat replies.
const SITE_OLLAMA_MODEL = process.env.SITE_BUILDER_OLLAMA_MODEL || (LocalLLM && LocalLLM.OLLAMA_MODEL) || "llama3.2:3b";

async function tryLocalOllama(cleanType, cleanName, onDelta) {
  if (!LocalLLM || !LocalLLM.isLocalMode()) return null;
  const serving = await LocalLLM.isOllamaServing().catch(() => false);
  if (!serving) return null;
  const pulled = await LocalLLM.isModelPulled(SITE_OLLAMA_MODEL).catch(() => false);
  if (!pulled) {
    console.warn(`[site-builder] Ollama is running but "${SITE_OLLAMA_MODEL}" isn't pulled — run: ollama pull ${SITE_OLLAMA_MODEL}. Falling back to Groq.`);
    return null;
  }
  const messages = [
    { role: "system", content: SYSTEM_PROMPT_FULL },
    { role: "user", content: `Business type: ${cleanType}\nBusiness name: ${cleanName}\nBuild the full single-file website now.` },
  ];
  // Ollama's bridge here doesn't stream — send the whole thing as one
  // delta so the build window still shows *something* land, just not
  // token-by-token. No TPM ceiling locally, so we can ask for a lot.
  const raw = await LocalLLM.ollamaText(messages, SITE_OLLAMA_MODEL, 0.85, 16000);
  const html = extractHtml(raw);
  if (typeof onDelta === "function") onDelta(html, { local: true });
  return html;
}

// Groq's free/on_demand tier for qwen/qwen3.6-27b caps at 8000 TPM —
// and that limit is charged against system+user+max_tokens REQUESTED,
// not just what's actually generated. So this path always uses the
// compact prompt and keeps max_tokens conservative enough to leave
// headroom, and if Groq still says the request is too large (a 413),
// retries once with an even smaller budget instead of just dying.
async function tryGroq(cleanType, cleanName, onDelta, onStreamStart) {
  if (!Hermes || !Hermes.isConfigured()) throw new Error("Build AI isn't configured — set GROQ_API_KEY in .env");
  const userMsg = { role: "user", content: `Business type: ${cleanType}\nBusiness name: ${cleanName}\nBuild the full single-file website now.` };

  const attempt = async (systemPrompt, maxTokens) => {
    const messages = [{ role: "system", content: systemPrompt }, userMsg];
    return typeof onDelta === "function"
      ? await Hermes.groqFetchStream(messages, {
          model: Hermes.MODELS.code, temperature: 0.85, maxTokens,
          onDelta: (d) => { onStreamStart(); onDelta(d); },
        })
      : await Hermes.groqFetch(messages, Hermes.MODELS.code, 0.85, maxTokens);
  };

  try {
    return extractHtml(await attempt(SYSTEM_PROMPT_COMPACT, 6000));
  } catch (e) {
    const tooLarge = /413|too large|reduce your message size/i.test(e.message || "");
    if (!tooLarge) throw e;
    console.warn(`[site-builder] Groq request still too large, retrying with a smaller budget: ${e.message}`);
    return extractHtml(await attempt(PROMPT_CORE, 3200));
  }
}

// ── BUILD ─────────────────────────────────────────────────────
async function buildSite(businessType, name, onDelta) {
  const cleanName = (name || "").trim();
  const cleanType = (businessType || "business").trim();
  if (!cleanName) throw new Error("A business name is required");

  let html;
  let streamedAny = false;
  try {
    html = await tryLocalOllama(cleanType, cleanName, onDelta);
    if (!html) html = await tryGroq(cleanType, cleanName, onDelta, () => { streamedAny = true; });
  } catch (e) {
    // Log the real reason so a run of fallbacks is diagnosable instead
    // of silently looking like "the AI just makes bad sites" — e.g. a
    // missing/invalid GROQ_API_KEY, an unrecognized model id, or a rate
    // limit will all land here.
    console.error(`[site-builder] generation failed for "${cleanName}":`, e.message);
    // Only substitute the fallback template if nothing had streamed yet —
    // once real tokens are already in the window, restarting mid-stream
    // would just garble what's on screen instead of recovering it.
    if (streamedAny) throw e;
    html = fallbackHtml(cleanType, cleanName);
    if (typeof onDelta === "function") onDelta(html, { fallback: true });
  }

  const slug = slugify(cleanName);
  const dir = path.join(SITES_DIR, slug);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, "index.html"), html, "utf8");

  // Write a real (if minimal) backend alongside the frontend. The live
  // preview never touches this — /sites is served as static files — but
  // it's sitting in the folder for when the site is downloaded and the
  // user wants the contact form to actually go somewhere.
  const backend = backendFiles(cleanName, cleanType, slug);
  for (const [filename, contents] of Object.entries(backend)) {
    fs.writeFileSync(path.join(dir, filename), contents, "utf8");
  }

  const entry = {
    slug, name: cleanName, businessType: cleanType, createdAt: Date.now(),
    url: `/sites/${slug}/index.html`, hasBackend: true,
  };
  const registry = loadRegistry();
  registry.unshift(entry);
  saveRegistry(registry.slice(0, 200)); // keep it bounded

  return entry;
}

// ── LOOKUP ────────────────────────────────────────────────────
// Fuzzy-ish: exact name match wins, then case-insensitive substring
// either direction, most recent first.
function findSiteByName(name) {
  const q = (name || "").trim().toLowerCase();
  if (!q) return null;
  const registry = loadRegistry();
  let hit = registry.find((s) => s.name.toLowerCase() === q);
  if (!hit) hit = registry.find((s) => s.name.toLowerCase().includes(q) || q.includes(s.name.toLowerCase()));
  return hit || null;
}

function listSites() { return loadRegistry(); }

// ── ZIP ───────────────────────────────────────────────────────
function zipSite(slug, destStream) {
  return new Promise((resolve, reject) => {
    const dir = path.join(SITES_DIR, slug);
    if (!fs.existsSync(dir)) return reject(new Error("No such site on disk"));
    const archive = archiver("zip", { zlib: { level: 9 } });
    archive.on("error", reject);
    archive.on("end", resolve);
    archive.pipe(destStream);
    archive.directory(dir, false);
    archive.finalize();
  });
}

module.exports = { buildSite, startBuild, streamBuild, findSiteByName, listSites, zipSite, SITES_DIR };
