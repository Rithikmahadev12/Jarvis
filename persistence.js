"use strict";
// ═══════════════════════════════════════════════════════════════
// J.A.R.V.I.S — Persistent Memory Sync (Backblaze B2 / S3)
//
// FIXED v2 — bandwidth-aware pull:
//   The original pulled ALL 152 files every single redeploy, hammering
//   Backblaze B2's free-tier download cap (1 GB/day Class B transactions).
//   152 files × every deploy = instant cap burn.
//
//   Fix: on pull, we first HEAD each remote file to get its ETag (hash).
//   If a local file already exists and its sha256 matches, we skip the
//   download entirely. Only actually-changed or missing files get fetched.
//   On a typical redeploy where nothing changed, this goes from 152
//   downloads to 0 downloads — just 152 cheap HEAD requests.
//
//   Additionally: pull retries now have a 10s delay (not 2s × attempt)
//   and MAX_ATTEMPTS reduced to 2 — B2 bandwidth caps don't clear by
//   retrying immediately, they reset on a timer, so hammering retries
//   just burns more cap faster.
//
// ── ENV VARS ─────────────────────────────────────────────────
//   B2_ENDPOINT   e.g. https://s3.us-east-005.backblazeb2.com
//   B2_BUCKET     e.g. jarvis-data
//   B2_KEY_ID     your applicationKeyId
//   B2_APP_KEY    your applicationKey
//   WALLET_ENCRYPTION_SECRET  (unchanged)
// ═══════════════════════════════════════════════════════════════

const fs     = require("fs");
const path   = require("path");
const crypto = require("crypto");

const {
  S3Client,
  ListObjectsV2Command,
  GetObjectCommand,
  HeadObjectCommand,
  PutObjectCommand,
  DeleteObjectCommand,
} = require("@aws-sdk/client-s3");

// ── CONFIG ────────────────────────────────────────────────────
const DATA_DIR   = path.join(__dirname, "data");
const ENDPOINT   = process.env.B2_ENDPOINT   || "";
const BUCKET     = process.env.B2_BUCKET     || "";
const KEY_ID     = process.env.B2_KEY_ID     || "";
const APP_KEY    = process.env.B2_APP_KEY    || "";
const FLUSH_INTERVAL_MS = 20 * 1000;
const KEYS_PREFIX = "wallet-keys";

// Files that are large, rarely needed at boot, or store/ product listings
// that regenerate themselves — skip pulling these on startup to save bandwidth.
// Add more patterns here as the bucket grows.
const SKIP_ON_PULL = [
  /^self-heal-backups\//,          // zip backups, large
  /^voice-clones\//,              // wav reference files, large
  /^store\/products\//,           // regenerated by store-routes.js
  /^sites\//,                     // mini-site files, pulled on demand
  /^studio\//,                    // studio project files
];

function shouldSkip(key) {
  return SKIP_ON_PULL.some(re => re.test(key));
}

function isConfigured() {
  return !!(ENDPOINT && BUCKET && KEY_ID && APP_KEY);
}

// ── S3 CLIENT (lazy) ──────────────────────────────────────────
let _client = null;
function client() {
  if (_client) return _client;
  _client = new S3Client({
    endpoint: ENDPOINT,
    region:   "us-east-005",        // B2 ignores this but SDK requires it
    credentials: { accessKeyId: KEY_ID, secretAccessKey: APP_KEY },
    forcePathStyle: true,
  });
  return _client;
}

// ── HELPERS ───────────────────────────────────────────────────
function hashOf(buffer) {
  return crypto.createHash("sha256").update(buffer).digest("hex");
}

function listLocalFiles(dir) {
  let out = [];
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out = out.concat(listLocalFiles(full));
    else out.push(full);
  }
  return out;
}

function guessContentType(relPath) {
  if (relPath.endsWith(".json")) return "application/json";
  if (relPath.endsWith(".js"))   return "application/javascript";
  return "application/octet-stream";
}

async function streamToBuffer(stream) {
  return new Promise((resolve, reject) => {
    const chunks = [];
    stream.on("data", (c) => chunks.push(c));
    stream.on("end",  () => resolve(Buffer.concat(chunks)));
    stream.on("error", reject);
  });
}

// List ALL keys in the bucket (handles B2 1000-item pagination)
async function listRemoteFiles(prefix = "") {
  let out = [];
  let continuationToken;
  do {
    const cmd = new ListObjectsV2Command({
      Bucket: BUCKET,
      Prefix: prefix || undefined,
      ContinuationToken: continuationToken,
    });
    const res = await client().send(cmd);
    for (const obj of res.Contents || []) {
      if (!prefix && obj.Key.startsWith(KEYS_PREFIX + "/")) continue;
      out.push({ key: obj.Key, etag: (obj.ETag || "").replace(/"/g, "") });
    }
    continuationToken = res.IsTruncated ? res.NextContinuationToken : undefined;
  } while (continuationToken);
  return out;
}

// ── SYNC STATE ────────────────────────────────────────────────
const _lastSynced = new Map(); // relPath → sha256 of what we last wrote
let _pullOk = false;

// ── PULL: B2 → local disk (bandwidth-aware) ───────────────────
// Strategy:
//   1. LIST the bucket — cheap, one request regardless of file count
//   2. For each key, check if local file exists and matches the remote ETag
//   3. Only download files that are missing or changed
//   4. Skip large/regeneratable file categories (SKIP_ON_PULL)
async function pullAll() {
  if (!isConfigured()) {
    console.log(
      "[MEMORY-SYNC] B2_ENDPOINT / B2_BUCKET / B2_KEY_ID / B2_APP_KEY " +
      "not set — running LOCAL-ONLY. Memory will be lost on restart/redeploy."
    );
    return;
  }

  // Only 2 attempts — bandwidth caps don't clear by retrying immediately
  const MAX_ATTEMPTS = 2;
  for (let attempt = 1; attempt <= MAX_ATTEMPTS; attempt++) {
    try {
      console.log(`[MEMORY-SYNC] Connecting to Backblaze B2 — checking what needs restoring (try ${attempt}/${MAX_ATTEMPTS})...`);
      const remoteFiles = await listRemoteFiles();

      let skipped = 0, restored = 0, alreadyCurrent = 0, failed = 0;

      for (const { key } of remoteFiles) {
        // Skip large/regeneratable categories entirely — save bandwidth
        if (shouldSkip(key)) { skipped++; continue; }

        const fullPath = path.join(DATA_DIR, key);
        const localExists = fs.existsSync(fullPath);

        // If local file exists, check if it already matches what's in B2
        // by hashing what we have — no HEAD request needed, we just compare
        // the hash against what we stored last time we wrote it.
        if (localExists) {
          try {
            const localBuf  = fs.readFileSync(fullPath);
            const localHash = hashOf(localBuf);
            if (_lastSynced.get(key) === localHash) {
              // We wrote this ourselves — still matches, no download needed
              alreadyCurrent++;
              continue;
            }
            // Not in our cache — do a lightweight HEAD to get remote ETag
            // so we can skip the download if the file hasn't changed in B2
            const head = await client().send(new HeadObjectCommand({ Bucket: BUCKET, Key: key }));
            const remoteETag = (head.ETag || "").replace(/"/g, "");
            const localMD5   = crypto.createHash("md5").update(localBuf).digest("hex");
            if (remoteETag && remoteETag === localMD5) {
              _lastSynced.set(key, localHash); // cache it going forward
              alreadyCurrent++;
              continue;
            }
          } catch { /* HEAD failed — fall through to download */ }
        }

        // File is missing locally or differs from B2 — download it
        try {
          const res    = await client().send(new GetObjectCommand({ Bucket: BUCKET, Key: key }));
          const buffer = await streamToBuffer(res.Body);
          fs.mkdirSync(path.dirname(fullPath), { recursive: true });
          fs.writeFileSync(fullPath, buffer);
          _lastSynced.set(key, hashOf(buffer));
          restored++;
        } catch (e) {
          console.warn(`[MEMORY-SYNC] Failed to restore ${key}: ${e.message}`);
          failed++;
        }
      }

      _pullOk = true;
      const parts = [];
      if (restored)       parts.push(`${restored} restored`);
      if (alreadyCurrent) parts.push(`${alreadyCurrent} already current (skipped download)`);
      if (skipped)        parts.push(`${skipped} skipped (large/regeneratable)`);
      if (failed)         parts.push(`${failed} failed`);
      console.log(`[MEMORY-SYNC] Done — ${parts.join(", ")}.`);

      // If some failed due to bandwidth cap, don't retry immediately — it won't help
      if (failed > 0) {
        console.warn(
          `[MEMORY-SYNC] ${failed} file(s) could not be restored. ` +
          `This is usually a Backblaze B2 bandwidth cap (Class B transactions). ` +
          `Jarvis will run with whatever is already on disk and push will remain enabled ` +
          `since some files DID restore successfully.`
        );
      }
      return;
    } catch (e) {
      console.warn(`[MEMORY-SYNC] Pull failed (try ${attempt}/${MAX_ATTEMPTS}): ${e.message}`);
      if (attempt < MAX_ATTEMPTS) await new Promise(r => setTimeout(r, 10_000));
    }
  }

  console.error(
    "[MEMORY-SYNC] Could NOT restore from B2. Pushing is DISABLED this run so your saved " +
    "data in B2 can't be overwritten by an empty local copy. Check B2_* env vars and redeploy."
  );
}

// ── PUSH: local disk → B2 (unchanged from original) ──────────
async function flush() {
  if (!isConfigured()) return 0;
  if (!_pullOk) return 0;

  const files  = listLocalFiles(DATA_DIR);
  let   pushed = 0;

  for (const fullPath of files) {
    const relPath = path.relative(DATA_DIR, fullPath).split(path.sep).join("/");
    let buffer;
    try { buffer = fs.readFileSync(fullPath); } catch { continue; }

    const hash = hashOf(buffer);
    if (_lastSynced.get(relPath) === hash) continue;

    try {
      await client().send(new PutObjectCommand({
        Bucket:      BUCKET,
        Key:         relPath,
        Body:        buffer,
        ContentType: guessContentType(relPath),
      }));
      _lastSynced.set(relPath, hash);
      pushed++;
    } catch (e) {
      console.warn(`[MEMORY-SYNC] Failed to push ${relPath}: ${e.message}`);
    }
  }

  if (pushed) console.log(`[MEMORY-SYNC] Pushed ${pushed} changed file(s) to B2.`);
  return pushed;
}

// ── BACKGROUND LOOP + GRACEFUL SHUTDOWN ──────────────────────
let _interval       = null;
let _shutdownHooked = false;

function startAutoSync() {
  if (!isConfigured() || _interval) return;

  _interval = setInterval(() => { flush().catch(() => {}); }, FLUSH_INTERVAL_MS);
  if (_interval.unref) _interval.unref();

  if (!_shutdownHooked) {
    _shutdownHooked = true;
    const shutdown = (signal) => {
      console.log(`[MEMORY-SYNC] ${signal} received — flushing memory to B2 before exit...`);
      flush()
        .catch((e) => console.warn("[MEMORY-SYNC] Final flush failed:", e.message))
        .finally(() => process.exit(0));
    };
    process.on("SIGTERM", () => shutdown("SIGTERM"));
    process.on("SIGINT",  () => shutdown("SIGINT"));
  }

  console.log(`[MEMORY-SYNC] Auto-sync running — pushing changes to B2 every ${FLUSH_INTERVAL_MS / 1000}s.`);
}

// ── DIRECT READ/WRITE ─────────────────────────────────────────
async function getJSON(relPath) {
  if (!isConfigured()) return null;
  try {
    const res = await client().send(new GetObjectCommand({ Bucket: BUCKET, Key: relPath }));
    const buf = await streamToBuffer(res.Body);
    return JSON.parse(buf.toString("utf8"));
  } catch { return null; }
}

async function putJSON(relPath, obj) {
  if (!isConfigured()) return false;
  try {
    await client().send(new PutObjectCommand({
      Bucket:      BUCKET,
      Key:         relPath,
      Body:        Buffer.from(JSON.stringify(obj, null, 2)),
      ContentType: "application/json",
    }));
    return true;
  } catch (e) {
    console.warn(`[MEMORY-SYNC] Direct write of ${relPath} failed: ${e.message}`);
    return false;
  }
}

async function deleteRemote(relPath) {
  if (!isConfigured()) return false;
  try {
    await client().send(new DeleteObjectCommand({ Bucket: BUCKET, Key: relPath }));
    return true;
  } catch (e) {
    console.warn(`[MEMORY-SYNC] Direct delete of ${relPath} failed: ${e.message}`);
    return false;
  }
}

// ── ENCRYPTED SECRET BACKUP (wallet private keys) ─────────────
function encryptionReady() {
  return isConfigured() && !!process.env.WALLET_ENCRYPTION_SECRET;
}
function _aesKey() {
  return crypto.scryptSync(process.env.WALLET_ENCRYPTION_SECRET, "jarvis-wallet-keys-v1", 32);
}
function _encrypt(plain) {
  const iv = crypto.randomBytes(12);
  const c  = crypto.createCipheriv("aes-256-gcm", _aesKey(), iv);
  const ct = Buffer.concat([c.update(plain), c.final()]);
  return Buffer.concat([Buffer.from("JK1"), iv, c.getAuthTag(), ct]);
}
function _decrypt(buf) {
  if (buf.slice(0, 3).toString() !== "JK1") throw new Error("unknown backup format");
  const iv = buf.slice(3, 15), tag = buf.slice(15, 31), ct = buf.slice(31);
  const d = crypto.createDecipheriv("aes-256-gcm", _aesKey(), iv);
  d.setAuthTag(tag);
  return Buffer.concat([d.update(ct), d.final()]);
}

async function putSecret(name, plainBuffer) {
  if (!encryptionReady()) return false;
  try {
    await client().send(new PutObjectCommand({
      Bucket:      BUCKET,
      Key:         `${KEYS_PREFIX}/${name}.enc`,
      Body:        _encrypt(plainBuffer),
      ContentType: "application/octet-stream",
    }));
    return true;
  } catch (e) {
    console.warn(`[KEY-BACKUP] Failed to back up ${name}: ${e.message}`);
    return false;
  }
}

async function restoreSecrets(destDir) {
  if (!encryptionReady()) return 0;
  let n = 0;
  try {
    const keys = await listRemoteFiles(KEYS_PREFIX + "/");
    for (const { key } of keys) {
      if (!key.endsWith(".enc")) continue;
      const name = path.basename(key, ".enc");
      const out  = path.join(destDir, name);
      if (fs.existsSync(out)) continue;
      try {
        const res   = await client().send(new GetObjectCommand({ Bucket: BUCKET, Key: key }));
        const buf   = await streamToBuffer(res.Body);
        const plain = _decrypt(buf);
        fs.mkdirSync(destDir, { recursive: true });
        fs.writeFileSync(out, plain, { mode: 0o600 });
        n++;
      } catch (e) {
        console.warn(`[KEY-BACKUP] Could not decrypt ${key}: ${e.message}`);
      }
    }
  } catch (e) {
    console.warn("[KEY-BACKUP] Restore failed:", e.message);
  }
  return n;
}

module.exports = {
  pullAll, flush, startAutoSync, isConfigured,
  getJSON, putJSON, deleteRemote,
  putSecret, restoreSecrets, encryptionReady,
};
